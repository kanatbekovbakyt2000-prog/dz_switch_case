// Две задачи без консольного ввода:
// 1) кофемашина (switch по String-жетону); 2) календарь (рабочий день или выходной).

void main() {
  print('===== Задание №1: Кофемашина =====');

  String token = 'латте';

  switch (token) {
    case 'эспрессо':
      print('Ваш напиток: эспрессо');
      break;
    case 'латте':
      print('Ваш напиток: латте');
      break;
    case 'капучино':
      print('Ваш напиток: капучино');
      break;
    default:
      print('Жетон не распознан, деньги возвращены');
  }
  print('');

  print('===== Задание №2: Календарь =====');

  String day = 'суббота';

  switch (day) {
    case 'понедельник':
    case 'вторник':
    case 'среда':
    case 'четверг':
    case 'пятница':
      print('$day: рабочий день');
      break;
    case 'суббота':
    case 'воскресенье':
      print('$day: выходной');
      break;
    default:
      print('Такого дня недели нет');
  }
}